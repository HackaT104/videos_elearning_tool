import { chromium } from "playwright";
const S = process.env.S;
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
await p.goto("http://localhost:3000/");
await p.fill('input[placeholder^="Tín chỉ"]', "Tín chỉ carbon & Tiêu chuẩn VCS");
await p.fill('input[placeholder="CAR"]', "CAR");
await p.getByText("Trung cấp (L2)").click();
await p.getByRole("button", { name: "Tạo dự án" }).click();
await p.waitForURL(/\/nguon/);
await p.setInputFiles('input[type=file]', ["fixtures/Kich_ban_L1.docx", "fixtures/Outline_L2.docx"]);
await p.waitForTimeout(500);
await p.getByRole("button", { name: /Tải lên/ }).click();
await p.getByText("Kết quả bóc").waitFor();
await p.screenshot({ path: `${S}/ui-1.png`, fullPage: true });
// L2 xlsx
await p.selectOption("select", "L2");
await p.setInputFiles('input[type=file]', ["fixtures/Kich_ban_L2.xlsx"]);
await p.getByText("Ghép cột").waitFor();
await p.screenshot({ path: `${S}/ui-1b.png`, fullPage: true });
await p.getByRole("button", { name: /Tải lên/ }).click();
await p.waitForTimeout(1500);
await p.getByRole("link", { name: "2 · Phân tích" }).click();
await p.getByText("Cần làm").waitFor();
await p.screenshot({ path: `${S}/ui-2.png`, fullPage: true });
const url = p.url();
await p.goto(url.replace("phan-tich", "kich-ban/CAR-L1_MO1_U1.5_1"));
await p.getByText("Lời thoại (hiển thị)").first().waitFor();
await p.screenshot({ path: `${S}/ui-3.png` });
await p.goto(url.replace("phan-tich", "doc"));
await p.getByText("Trước (lời thoại)").waitFor();
await p.screenshot({ path: `${S}/ui-4.png` });
console.log(url, errs);
await b.close();
