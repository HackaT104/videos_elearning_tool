// Chạy thử toàn bộ 10 bước qua giao diện và chụp ảnh từng bước (cần worker + web đang chạy).
import { chromium } from "playwright";
const S = process.env.S ?? ".";
const BASE = process.env.BASE ?? "http://localhost:3000";
const W = { width: 1280, height: 860 };
const b = await chromium.launch();
const p = await b.newPage({ viewport: W });
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
const shot = (n) => p.screenshot({ path: `${S}/demo-${n}.png`, fullPage: false });
const api = async (path, init) => (await fetch(`${BASE}/api${path}`, init)).json();

await p.goto(`${BASE}/`);
await p.fill('input[placeholder^="Tín chỉ"]', "Tín chỉ carbon & Tiêu chuẩn VCS");
await p.fill('input[placeholder="CAR"]', "CAR");
await shot("00-du-an-moi");
await p.getByRole("button", { name: "Tạo dự án" }).click();
await p.waitForURL(/\/nguon/);
const pid = p.url().split("/p/")[1].split("/")[0];
await p.setInputFiles("input[type=file]", ["fixtures/Kich_ban_L1.docx"]);
await p.getByRole("button", { name: /Tải lên/ }).click();
await p.getByText("Kết quả bóc").waitFor();
await shot("01-tai-tai-lieu");
await p.goto(`${BASE}/p/${pid}/phan-tich`);
await p.getByText("Cần làm").waitFor();
await shot("02-phan-tich");
await p.goto(`${BASE}/p/${pid}/kich-ban/CAR-L1_MO1_U1.5_1`);
await p.getByText("Lời thoại (hiển thị)").first().waitFor();
await shot("03-kich-ban");
await p.goto(`${BASE}/p/${pid}/doc`);
await p.getByText("Trước (lời thoại)").waitFor();
await shot("04-soat-cach-doc");
await p.goto(`${BASE}/p/${pid}/giong`);
await p.getByText("Cấu hình theo cấp độ").waitFor();
await p.waitForTimeout(1500);
await shot("05-giong-nhip");
await p.goto(`${BASE}/p/${pid}/phong-cach`);
await p.getByRole("button", { name: "Dựng cùng khung theo 5 kiểu" }).click();
await p.getByRole("button", { name: "Dựng cùng khung theo 5 kiểu" }).waitFor({ timeout: 240000 });
await p.waitForTimeout(2500);
await p.screenshot({ path: `${S}/demo-06-phong-cach.png`, fullPage: true });
await p.goto(`${BASE}/p/${pid}/san-xuat`);
await p.getByRole("button", { name: /Sản xuất tất cả/ }).click();
await p.waitForTimeout(15000);
await shot("07-san-xuat");
for (let i = 0; i < 400; i++) {
  const vs = await api(`/projects/${pid}/videos`);
  if (vs.every((v) => v.rendered && !v.job)) break;
  await p.waitForTimeout(3000);
}
await p.goto(`${BASE}/p/${pid}/duyet/CAR-L1_MO1_U1.5_1`);
await p.getByText("Báo cáo QA").waitFor();
await p.waitForTimeout(2000);
await shot("08-xem-duyet");
for (const k of ["CAR-L1_MO1_U1.5_1", "CAR-L1_MO2_U2.2_1"]) await api(`/projects/${pid}/videos/${k}`, { method: "PATCH", headers: { "content-type": "application/json" }, body: JSON.stringify({ approve: true, override: true }) });
await p.goto(`${BASE}/p/${pid}/xuat`);
await p.getByRole("button", { name: /Xuất 2 video/ }).click();
await p.getByText("Đã xuất 2 video").waitFor();
await shot("09-xuat");
await p.goto(`${BASE}/p/${pid}/don-dep`);
await p.waitForTimeout(2000);
await shot("10-don-dep");
console.log(JSON.stringify({ pid, errs }));
await b.close();
